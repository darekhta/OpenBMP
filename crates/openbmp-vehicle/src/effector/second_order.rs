    fn servo_sine_fundamental(
        input_amplitude: f64,
        frequency_hz: f64,
        max_rate_per_s: f64,
        backlash_half_width: f64,
    ) -> RateLimitBacklashDescribingFunction {
        let dt_s = 1.0 / (frequency_hz * DESCRIBING_FUNCTION_SAMPLES_PER_CYCLE as f64);
        let dt = Duration::from_seconds(dt_s);
        let limits = EffectorLimits {
            min: -2.0,
            max: 2.0,
            max_rate_per_s,
            deadband: 0.0,
            latency: Duration::from_seconds(0.0),
        };
        let params = SecondOrderServoParams {
            natural_frequency_rad_s: 2_500.0,
            damping_ratio: 1.0,
            max_accel_per_s2: 1.0e12,
            backlash_half_width,
        };
        let mut servo =
            SecondOrderServo::new(EffectorId::from_path("test.df"), limits, params, dt, 0.0)
                .unwrap();
        let final_cycle_start =
            DESCRIBING_FUNCTION_WARMUP_CYCLES * DESCRIBING_FUNCTION_SAMPLES_PER_CYCLE;
        let total_steps = final_cycle_start + DESCRIBING_FUNCTION_SAMPLES_PER_CYCLE;
        let samples = DESCRIBING_FUNCTION_SAMPLES_PER_CYCLE as f64;
        let mut sin_sum = 0.0;
        let mut cos_sum = 0.0;
        let mut rate_limited_steps = 0_usize;

        for step in 0..total_steps {
            let theta = std::f64::consts::TAU * frequency_hz * (step as f64) * dt_s;
            let command = input_amplitude * theta.sin();
            let state = servo.step(command, dt).unwrap();
            if step >= final_cycle_start {
                sin_sum += state.actual * theta.sin();
                cos_sum += state.actual * theta.cos();
                if state.rate_limited {
                    rate_limited_steps += 1;
                }
            }
        }

        let sin_coeff = 2.0 * sin_sum / samples;
        let cos_coeff = 2.0 * cos_sum / samples;
        let output_amplitude = sin_coeff.hypot(cos_coeff);
        RateLimitBacklashDescribingFunction {
            input_amplitude,
            frequency_hz,
            output_amplitude,
            gain: output_amplitude / input_amplitude,
            phase_lag_rad: wrap_angle_rad(-cos_coeff.atan2(sin_coeff)),
            rate_limited_fraction: rate_limited_steps as f64 / samples,
            backlash_hold_fraction: 0.0,
        }
    }

    #[test]
    fn rate_limit_backlash_fundamental_matches_describing_function() {
        let input_amplitude = 1.0;
        let frequency_hz = 2.0;
        let max_rate_per_s = 4.0;
        let backlash_half_width = 0.08;
        let expected = rate_limit_backlash_describing_function(
            input_amplitude,
            frequency_hz,
            max_rate_per_s,
            backlash_half_width,
        )
        .unwrap();
        assert!(expected.rate_limited_fraction > 0.9);
        assert!(expected.backlash_hold_fraction > 0.1);

        let measured = servo_sine_fundamental(
            input_amplitude,
            frequency_hz,
            max_rate_per_s,
            backlash_half_width,
        );
        let amplitude_error = (measured.output_amplitude - expected.output_amplitude).abs()
            / expected.output_amplitude;
        let phase_error = wrap_angle_rad(measured.phase_lag_rad - expected.phase_lag_rad).abs();
        assert!(
            amplitude_error <= 0.05,
            "measured amplitude {} differs from describing-function {} by {:.3}%",
            measured.output_amplitude,
            expected.output_amplitude,
            amplitude_error * 100.0
        );
        assert!(
            phase_error <= 0.05,
            "measured phase lag {} differs from describing-function {} by {phase_error}",
            measured.phase_lag_rad,
            expected.phase_lag_rad
        );
        assert!((measured.frequency_hz - expected.frequency_hz).abs() <= f64::EPSILON);
    }

