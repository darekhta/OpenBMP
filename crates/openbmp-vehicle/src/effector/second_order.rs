    #[test]
    fn step_response_matches_closed_form_second_order() {
        let mut servo = fresh_servo();
        let target = 1.0;
        let steps = 1_000;
        for _ in 0..steps {
            servo.step(target, dt()).unwrap();
        }

        let t = f64::from(steps) * dt().as_seconds();
        let zeta = make_params().damping_ratio;
        let omega_n = make_params().natural_frequency_rad_s;
        let omega_d = omega_n * (1.0 - zeta * zeta).sqrt();
        let expected = target
            * (1.0
                - (-zeta * omega_n * t).exp()
                    * ((omega_d * t).cos()
                        + (zeta / (1.0 - zeta * zeta).sqrt()) * (omega_d * t).sin()));
        let error = (servo.current_state().actual - expected).abs();
        assert!(
            error <= 5.0e-3,
            "step response error {error} exceeds 0.5% band; actual {}, expected {expected}",
            servo.current_state().actual
        );
    }

